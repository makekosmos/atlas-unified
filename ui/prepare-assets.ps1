# Turns the SVGs in ../assets/icons into ui/icons.ts, the data URIs the UI
# draws them from. The pairs are in ui/icons.json: "dooicons" holds the names
# fetch-icons.ps1 downloads, "local" the SVGs kept in the repo as they are.
# Run it after adding a name to icons.json.
$root = Split-Path -Parent $PSScriptRoot
$spec = Get-Content (Join-Path $PSScriptRoot 'icons.json') -Raw | ConvertFrom-Json
$files = [ordered]@{}
foreach ($entry in $spec.dooicons.PSObject.Properties) {
    $files[$entry.Name] = "$($entry.Value).svg"
}
foreach ($entry in $spec.local.PSObject.Properties) {
    $files[$entry.Name] = $entry.Value
}
$lines = foreach ($entry in $files.GetEnumerator()) {
    $svg = Get-Content (Join-Path $root "assets/icons/$($entry.Value)") -Raw
    $encoded = [Uri]::EscapeDataString($svg)
    "  $($entry.Key): `"data:image/svg+xml,$encoded`","
}
$out = @(
    '/// The app''s icons as data URIs; generated by prepare-assets.ps1 from',
    '/// the dooicons set (https://dooicons.vercel.app), do not edit by hand.',
    'export const glyphs = {'
) + $lines + @(
    '} as const;',
    '',
    'export type GlyphName = keyof typeof glyphs;'
)
Set-Content -Encoding utf8 (Join-Path $PSScriptRoot 'icons.ts') $out
