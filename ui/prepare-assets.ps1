# Turns the Hugeicons SVGs the app ships (../assets/icons, the same set imago
# uses) into ui/icons.ts, the data URIs the UI draws them from. Run it after
# adding a name to $names.
$names = [ordered]@{
    search = 'search.svg'
    folder = 'folder-open.svg'
    file   = 'task-01.svg'
    check  = 'check.svg'
    close  = 'window-close.svg'
    gamepad = 'gamepad.svg'
}
$lines = foreach ($entry in $names.GetEnumerator()) {
    $svg = Get-Content (Join-Path $PSScriptRoot "../assets/icons/$($entry.Value)") -Raw
    $encoded = [Uri]::EscapeDataString($svg)
    "  $($entry.Key): `"data:image/svg+xml,$encoded`","
}
$out = @(
    '/// The app''s line icons (Hugeicons) as data URIs; generated by',
    '/// prepare-assets.ps1, do not edit by hand.',
    'export const glyphs = {'
) + $lines + @(
    '} as const;',
    '',
    'export type GlyphName = keyof typeof glyphs;'
)
Set-Content -Encoding utf8 (Join-Path $PSScriptRoot 'icons.ts') $out
